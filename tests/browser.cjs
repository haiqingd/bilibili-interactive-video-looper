/* Optional end-to-end UI verification against a running local service. */
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const url = process.env.LOOPER_URL || 'http://127.0.0.1:8787';

(async () => {
  const browser = await chromium.launch({executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless:true, args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1080}});
  const errors = [];
  page.on('pageerror', e=>errors.push(e.message));
  page.on('console', m=>{if(m.type()==='error')errors.push(m.text());});
  const output = path.join(__dirname,'..','artifacts');fs.mkdirSync(output,{recursive:true});
  try {
    await page.goto(url);
    await page.locator('#demo-button').click();
    await page.locator('#result:not([hidden])').waitFor();
    await page.waitForTimeout(400);
    await page.locator('[data-ending="good"]').click();
    assert.equal(await page.locator('#route-steps li').count(),7);
    assert.equal(await page.locator('#route-only').isChecked(),false);
    await page.locator('#route-only').check();
    assert.equal(await page.locator('.graph-edge.highlight').count(),7);
    await page.locator('#clear-route').click();
    await page.locator('[data-display="cycle:0"]').click();
    await page.locator('[data-node="loopA"]').first().click();
    assert.match(await page.locator('#node-detail').innerText(),/闭环/);
    await page.locator('#zoom-in').click();await page.locator('#fit-button').click();
    await page.locator('[data-view="list"]').click();
    assert.equal(await page.locator('.node-row').count(),11);
    await page.locator('[data-view="graph"]').click();
    const wasFavorite=(await page.locator('#favorite-button').innerText()).includes('已收藏');
    await page.locator('#favorite-button').click();
    await page.waitForFunction(expected=>document.querySelector('#favorite-button').textContent.includes('已收藏')===expected,!wasFavorite);
    await page.reload();await page.locator('#result:not([hidden])').waitFor();
    assert.equal((await page.locator('#favorite-button').innerText()).includes('已收藏'),!wasFavorite);
    const downloadEvent=page.waitForEvent('download');await page.locator('#export-button').click();
    const exported=await downloadEvent;
    const exportedPath=await exported.path();
    const graph=JSON.parse(fs.readFileSync(exportedPath,'utf8'));
    assert.equal(graph.nodes.length,11);
    await page.locator('[data-page="library"]').click();
    await page.locator('.library-card').first().waitFor();
    await page.locator('#library-search').fill('不存在的故事XYZ');
    assert.equal(await page.locator('.library-card').count(),0);
    await page.locator('#library-search').fill('雾港来信');
    const tagCard=page.locator('.library-card').filter({hasText:'雾港来信'}).first();
    page.once('dialog',dialog=>dialog.accept('浏览器测试, 悬疑'));
    await tagCard.locator('[data-action="tags"]').click();
    await page.locator('.tag').filter({hasText:'浏览器测试'}).waitFor();
    await page.locator('#tag-filter').selectOption('浏览器测试');
    assert.equal(await page.locator('.library-card').count(),1);
    await page.locator('#import-file').setInputFiles(exportedPath);
    await page.locator('#explore-page:not([hidden])').waitFor();
    await page.locator('#result:not([hidden])').waitFor();
    await page.locator('#clear-route').click();
    await page.waitForTimeout(3500);
    await page.screenshot({path:path.join(output,'desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.waitForTimeout(300);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
    await page.locator('#help-button').click();assert.equal(await page.locator('#help-dialog').isVisible(),true);
    await page.locator('#help-close').click();
    assert.deepEqual(errors,[]);
    console.log('Desktop/mobile, score route, trap, zoom, list, favorites, persistence, search, tags, export/import, and help: passed');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
